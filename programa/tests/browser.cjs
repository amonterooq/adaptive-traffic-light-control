const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');

(async () => {
  const out=process.env.ITS_SCREENSHOTS||path.resolve('documentacion/capturas');
  fs.mkdirSync(out,{recursive:true});
  const browser=await chromium.launch({headless:true,channel:process.env.ITS_BROWSER||undefined});
  const page=await browser.newPage({viewport:{width:1440,height:1100}});
  const errors=[],checks=[];page.on('pageerror',err=>errors.push(String(err)));
  const check=(label,condition)=>{assert.ok(condition,label);checks.push(label);};
  const endpoint=route=>new URL(route,page.url()).href;
  const state=async()=>await(await page.request.get(endpoint('/api/state'))).json();
  await page.goto(process.env.ITS_URL||'http://127.0.0.1:8765');
  await page.waitForFunction(()=>document.querySelectorAll('#map-features path').length>100&&window.sceneView?.geometry);
  check('mapa local y geometría SUMO',true);
  check('demostración preparada al abrir',await page.locator('#horizon').inputValue()==='120'&&await page.locator('#pedestrian-profile').inputValue()==='frecuente');
  await page.locator('#point-laboratorio button').click();
  await page.waitForFunction(()=>window.sceneView.geometry?.location==='laboratorio');
  await page.locator('#advanced-settings summary').click();
  await page.locator('#min-green').fill('35');await page.locator('#max-green').fill('20');await page.locator('#start').click();
  check('validación de parámetros',(await page.locator('#notice').textContent()).includes('mínimo'));
  await page.locator('#min-green').fill('10');await page.locator('#max-green').fill('50');
  await page.locator('#advanced-settings summary').click();
  await page.locator('#speed').selectOption('10');await page.locator('#start').click();
  await page.waitForFunction(()=>document.querySelector('#run-status').textContent==='En curso');
  check('ejecución real SUMO',true);
  await page.waitForFunction(()=>window.sceneView?.agents.some(a=>a.kind==='vehicle'&&a.speed>0),{},{timeout:20000});
  const first=await page.evaluate(()=>window.sceneView.agents.find(a=>a.kind==='vehicle'&&a.speed>0));
  await page.waitForFunction(a=>{const b=window.sceneView.agents.find(b=>b.id===a.id);return b&&Math.hypot(b.x-a.x,b.y-a.y)>1;},first);
  check('coches con posiciones que cambian',true);
  await page.locator('#speed').selectOption('20');
  await page.waitForFunction(()=>window.sceneView.speed===20);
  check('velocidad modificable en marcha',true);
  await page.waitForFunction(()=>window.sceneView.agents.some(a=>a.kind==='person'&&a.road.startsWith(':J1_c')),{},{timeout:20000});
  await page.locator('#pause').click();await page.waitForFunction(()=>window.sceneView.paused);
  await page.waitForTimeout(250);
  const paused=await page.evaluate(()=>({time:window.sceneView.time,agents:window.sceneView.agents.map(a=>[a.id,a.x,a.y])}));
  await page.waitForTimeout(350);
  check('pausa detiene tiempo y posiciones',JSON.stringify(paused)===JSON.stringify(await page.evaluate(()=>({time:window.sceneView.time,agents:window.sceneView.agents.map(a=>[a.id,a.x,a.y])}))));
  const live=await state();check('peatones cruzan con vehículos en rojo',live.sample.state==='rrrr'&&await page.evaluate(()=>window.sceneView.agents.some(a=>a.kind==='person'&&a.road.startsWith(':J1_c'))));
  check('coches detenidos visibles',await page.evaluate(()=>window.sceneView.agents.some(a=>a.kind==='vehicle'&&a.speed<.1)));
  await page.locator('#scene-zoom-in').click();check('zoom del cruce',await page.evaluate(()=>window.sceneView.radius<38));
  await page.locator('#scene-wide').click();check('vista de toda la red',await page.evaluate(()=>window.sceneView.radius===315));
  await page.locator('#scene-close').click();
  await page.evaluate(()=>new Promise(requestAnimationFrame));
  const selected=await page.evaluate(()=>{
    const v=window.sceneView;const a=v.agents.find(a=>a.kind==='person'&&a.road.startsWith(':J1_c'));
    const p=v.point(a.x,a.y),r=v.canvas.getBoundingClientRect();return {x:p[0]+r.left,y:p[1]+r.top};
  });
  await page.mouse.click(selected.x,selected.y);check('selección de peatón con datos reales',await page.locator('#entity-info').isVisible());
  await page.mouse.click(60,470);
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:path.join(out,'panel_resumen.png'),fullPage:false});
  await page.locator('.scene-card').screenshot({path:path.join(out,'vista_animada.png')});
  await page.screenshot({path:path.join(out,'panel_escritorio.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:path.join(out,'panel_movil.png'),fullPage:true});
  check('móvil sin desbordamiento',await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  await page.setViewportSize({width:1440,height:1100});
  await page.locator('#pause').focus();await page.keyboard.press('Space');await page.waitForFunction(()=>!window.sceneView.paused);
  check('reanudar mediante teclado',true);
  await page.waitForFunction(()=>document.querySelector('#run-status').textContent==='Completada',{},{timeout:30000});
  await page.waitForFunction(()=>window.sceneView.agents.length===0&&window.sceneView.status==='complete');
  const completed=await state();
  check('conservación y ausencia de conflictos',completed.summary.generated===completed.summary.arrived&&completed.summary.ped_generated===completed.summary.ped_arrived&&completed.summary.ped_conflicts===0);
  check('cruce vacío al finalizar',true);
  await page.locator('#refresh-history').click();await page.locator('#history-body button').first().click();
  await page.waitForFunction(()=>document.querySelector('#chart-caption').textContent.includes('Histórico'));
  check('histórico persistido',true);
  const csv=await page.request.get(endpoint(await page.locator('#history-body a').first().getAttribute('href')));
  const text=await csv.text();check('CSV de vehículos y peatones',csv.status()===200&&text.includes('q_n')&&text.includes('ped_crossing'));
  await page.locator('#map-context summary').click();const before=await page.locator('#map').getAttribute('viewBox');
  await page.locator('#zoom-in').click();check('mapa geográfico ampliable',await page.locator('#map').getAttribute('viewBox')!==before);
  await page.locator('#map-context summary').click();
  await page.locator('[data-tab=results]').click();await page.waitForSelector('.bar-row');
  check('cinco escenarios y cuatro perfiles comparables',await page.locator('#results-body tr').count()===5&&await page.locator('#ped-results-body tr').count()===4);
  await page.screenshot({path:path.join(out,'resultados_escritorio.png'),fullPage:true});
  await page.locator('[data-tab=guide]').click();check('guía accesible',await page.locator('#guide h1').isVisible());
  await page.locator('[data-tab=monitor]').click();await page.locator('#pedestrian-profile').selectOption('desactivado');
  await page.locator('#start').click();await page.waitForFunction(()=>window.sceneView.status==='running'&&!window.sceneView.enabled&&window.sceneView.agents.length>0);
  check('nueva ejecución sin peatones ni pasos',await page.evaluate(()=>window.sceneView.geometry.lanes.every(l=>l.kind!=='crossing')&&window.sceneView.agents.every(a=>a.kind==='vehicle')));
  await page.locator('#pause').click();await page.waitForFunction(()=>window.sceneView.paused);await page.locator('#stop').click();
  await page.waitForFunction(()=>document.querySelector('#run-status').textContent==='Cancelada');
  check('detener desde pausa',true);
  await page.route('**/api/scene?**',route=>route.abort());await page.waitForFunction(()=>!window.sceneView.connected);
  const frozen=await page.evaluate(()=>window.sceneView.time);
  await page.waitForTimeout(250);check('pérdida de conexión señalada',await page.locator('#scene-phase').textContent()==='Conexión interrumpida');
  await page.waitForTimeout(200);check('sin movimiento inventado al perder datos',await page.evaluate(()=>window.sceneView.time)===frozen);
  await page.unroute('**/api/scene?**');
  check('sin errores JavaScript',errors.length===0);
  fs.writeFileSync(path.join(out,'prueba_navegador.json'),JSON.stringify({passed:true,checks,date:new Date().toISOString()},null,2));
  console.log('Prueba de navegador superada, '+checks.length+' comprobaciones. Capturas:',out);
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
